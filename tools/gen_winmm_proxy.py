#!/usr/bin/env python3
"""Generate the winmm.dll proxy exports from Wine's winmm.spec.

Outputs (into ../WinmmProxy):
  proxy_stubs.cpp - one naked `jmp [px_table + N*4]` stub per export (MSVC and GCC/Clang)
  names.h         - export names, resolved with GetProcAddress at load time (proxy.cpp)
  winmm.def       - export table (PlaySoundA keeps ordinal 2 like the real DLL)

Usage: python3 tools/gen_winmm_proxy.py
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "WinmmProxy")

names, ords = [], {}
for line in open(os.path.join(here, "winmm.spec")):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    parts = line.split()
    if parts[1] == "stub":
        if parts[2] != "@":
            names.append(parts[2])
        continue
    m = re.match(r"(\S+)\s+stdcall\s+(?:-\S+\s+)*(\S+?)\(", line)
    ordinal, name = m.group(1), m.group(2)
    if name == "@":                      # ordinal-only export, real name is the last field
        ords[parts[-1]] = ordinal
        continue
    names.append(name)
names = sorted(set(names))

def write(name, text):
    with open(os.path.join(src, name), "w", newline="\n") as f:
        f.write(text)

stubs = [
    "// Generated by tools/gen_winmm_proxy.py - do not edit.",
    "// Each winmm export jumps through px_table (filled in proxy.cpp) to the real winmm.dll.",
    '#include "compat.hpp"',
    '#include "names.h"',
    "",
    'extern "C" void* px_table[PX_COUNT];',
    "",
    "#ifdef C1QOL_MS_ASM",
    "#define PX_STUB(name, i) \\",
    '    extern "C" C1QOL_NAKED void px_##name() { __asm { __asm jmp dword ptr [px_table + (i) * 4] } }',
    "#else",
    "#define PX_STUB(name, i) \\",
    '    extern "C" C1QOL_NAKED void px_##name() { __asm__("jmp *_px_table+" #i "*4"); }',
    "#endif",
    "",
]
stubs += [f"PX_STUB({n}, {i})" for i, n in enumerate(names)]
write("proxy_stubs.cpp", "\n".join(stubs) + "\n")

write("names.h",
      "// Generated by tools/gen_winmm_proxy.py - do not edit.\n#pragma once\n\n"
      "static const char* const px_names[] = {\n"
      + ",\n".join(f'    "{n}"' for n in names)
      + f"\n}};\n#define PX_COUNT {len(names)}\n")

write("winmm.def",
      "LIBRARY winmm.dll\nEXPORTS\n"
      + "".join(f"  {n}=px_{n}{' @' + ords[n] if n in ords else ''}\n" for n in names))

print(f"{len(names)} exports written to {os.path.normpath(src)}")
